// Regenerates docs/MUKAI_API.md from the endpoint catalog (run after `npm run build`).
import { writeFileSync } from 'node:fs';
import { endpoints } from '../dist/endpoints.js';
import { SENSITIVE_TOOLS } from '../dist/security.js';

const groups = {
  '': 'System', 'ai-activity': 'System', limits: 'System', health: 'System',
  workspaces: 'Workspaces & VM computers', bots: 'Bots', conversations: 'Conversations, spaces & chat',
  changes: 'Conversations, spaces & chat', artifacts: 'Files', attachments: 'Files', approvals: 'Approvals',
  providers: 'AI providers', pursuits: 'Pursuits (long-running goals)', memory: 'Memory',
  tools: 'Tools & custom capabilities', capabilities: 'Tools & custom capabilities', environment: 'Tools & custom capabilities',
  skills: 'Skills', browser: 'Browser', notifications: 'Notifications & failures', failures: 'Notifications & failures',
  settings: 'Settings & updates', telegram: 'Telegram',
};
const extra = [
  { method: 'POST', path: '/bots/{botId}/chat', name: 'mukai_chat_with_bot', description: 'Send a message to a bot and stream its reply.' },
  { method: 'POST', path: '/conversations/{conversationId}/chat', name: 'mukai_send_conversation_message', description: 'Send a message in any conversation and stream the reply.' },
  { method: 'POST', path: '/conversations/{conversationId}/retry', name: 'mukai_retry_conversation_message', description: 'Retry a failed/stopped response.' },
  { method: 'POST', path: '/bots/{botId}/attachments', name: 'mukai_upload_attachment', description: 'Upload a file (raw body + X-Filename).' },
  { method: 'POST', path: '/conversations/{conversationId}/attachments', name: 'mukai_upload_attachment', description: 'Upload a file into a conversation.' },
];
const all = [...endpoints, ...extra];
const byGroup = new Map();
for (const e of all) {
  const group = groups[e.path.split('/')[1] || ''] || 'Other';
  if (!byGroup.has(group)) byGroup.set(group, []);
  byGroup.get(group).push(e);
}
const order = [...new Set(Object.values(groups))];
let md = `# Mukai API inventory

Everything below is an existing route in Mukai's backend
(\`src/server/http/routes.ts\`, \`src/server/http/telegramRoutes.ts\` in munashesydney/mukai),
with the MCP tool that calls it. *Generated by \`scripts/gen-api-doc.mjs\`. Don't edit by hand.*

- **Auth:** every route except \`/health\` needs \`Authorization: Bearer <Mukai API token>\`.
- **Base URL:** \`http://127.0.0.1:47831\` locally, or \`https://<your-domain>/api\` behind \`mukai serve\`.
- **Workspace scope:** most routes take \`?workspaceId=\` (default \`default\`).
- **Chat** routes stream newline-delimited JSON events (\`start\`, \`delta\`, \`activity\`, \`approval\`, \`done\`/\`error\`).
- 🔒 = sensitive and ⚠️ = destructive. Both need human confirmation by default in the MCP server.

| | Count |
| --- | --- |
| Routes mapped to MCP tools | ${all.length} |

`;
for (const group of order) {
  const rows = byGroup.get(group);
  if (!rows) continue;
  md += `## ${group}\n\n| Method | Path | What it does | MCP tool |\n| --- | --- | --- | --- |\n`;
  for (const e of rows) {
    const flags = (SENSITIVE_TOOLS.has(e.name) ? ' 🔒' : '') + (e.destructive ? ' ⚠️' : '');
    md += `| ${e.method} | \`${e.path}\` | ${e.description.replace(/\|/g, '\\|').replace(/\n/g, ' ')} | \`${e.name}\`${flags} |\n`;
  }
  md += '\n';
}
md += `## Routes not exposed as dedicated tools

| Route | Why |
| --- | --- |
| \`GET /settings/api\` | Returns the backend API token itself. Blocked everywhere in the MCP server. |
| \`/push/*\` | Mobile push-device registration. Needs a per-device session header. |
| \`POST /workspaces/{id}/computer-view\`, \`/computer-audio\` | Tickets for the UI's WebSocket desktop/audio stream. |
| \`POST /environment/export\` | Downloads all workspace secrets as a .env file. Raw API only. |
| \`/custom/*\` | Routes that *your own* custom-route modules serve. They have their own auth. |
| \`/api/auth/*\`, \`/api/session\`, \`/api/instance\` | Browser login/session handling in \`mukai serve\`. |
`;
writeFileSync(new URL('../docs/MUKAI_API.md', import.meta.url), md);
console.log('wrote docs/MUKAI_API.md', all.length, 'routes');
